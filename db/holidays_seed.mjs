async function fetchYear(year) {
  const r = await fetch(url(year), { headers: { accept: 'application/json' } });
  if (!r.ok) throw new Error('hebcal ' + year + ' → HTTP ' + r.status);
  const j = await r.json();
  return (j.items || []).map(classify).filter(Boolean);
}

async function main() {
  let rows = [];
  let source = 'hebcal (live)';
  try {
    for (const y of YEARS) rows = rows.concat(await fetchYear(y));
    if (!rows.length) throw new Error('hebcal returned no major holidays');
  } catch (e) {
    console.warn('⚠️  Hebcal fetch failed (' + e.message + ') — using the built-in 2026–2027 list.');
    rows = FALLBACK.slice();
    source = 'built-in fallback list (network unavailable)';
  }
  // one row per date, ascending
  const byDate = new Map();
  for (const r of fillClosureGaps(rows)) byDate.set(r.date, r);
  const out = [...byDate.values()].sort((a, b) => a.date.localeCompare(b.date));
  if (process.argv.includes('--print')) { console.table(out); return; }
  writeFileSync(OUT, toSql(out), 'utf8');
  console.log(`✅ ${out.length} rows → ${OUT}  (source: ${source})`);
}

